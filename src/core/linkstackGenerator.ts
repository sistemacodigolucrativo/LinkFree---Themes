function buildBackgroundCss(cfg: ThemeConfig): string {
  const bg1 = cfg.colors.backgroundPrimary;
  const bg2 = cfg.colors.backgroundSecondary;
  const accent1 = hexToRgbaString(cfg.colors.accentPrimary, 0.24 * cfg.background.opacity);
  const accent2 = hexToRgbaString(cfg.colors.accentSecondary, 0.2 * cfg.background.opacity);

  if (cfg.background.effect === 'animated-gradient') {
    return `background: linear-gradient(135deg, ${bg1}, ${bg2}, ${hexToRgbaString(cfg.colors.accentPrimary, 0.22)}, ${bg1});
  background-size: 320% 320%;
  animation: lsGradientFlow ${Math.max(4, Math.round(14 / cfg.background.speed))}s ease infinite;`;
  }

  if (cfg.background.effect === 'aurora') {
    return `background:
    radial-gradient(ellipse 80% 50% at 20% 15%, ${accent1}, transparent 65%),
    radial-gradient(ellipse 70% 55% at 85% 75%, ${accent2}, transparent 65%),
    radial-gradient(ellipse at bottom, ${bg2} 0%, ${bg1} 100%);`;
  }

  if (cfg.background.effect === 'depth-glow') {
    return `background:
    radial-gradient(circle at 50% 18%, ${accent1}, transparent 52%),
    radial-gradient(circle at 50% 90%, ${accent2}, transparent 60%),
    linear-gradient(180deg, ${bg1} 0%, ${bg2} 100%);`;
  }

  return `background: radial-gradient(ellipse at top, ${bg2} 0%, ${bg1} 100%);`;
}

