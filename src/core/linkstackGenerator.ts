function escapePhpSingleQuote(val: string): string {
  return val.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

export function sanitizeSlug(name: string): string {
  const cleaned = name
    .replace(/[^a-zA-Z0-9_-]+/g, '')
    .replace(/^[-_]+|[-_]+$/g, '');
  return cleaned || 'FuturisticTheme';
}

