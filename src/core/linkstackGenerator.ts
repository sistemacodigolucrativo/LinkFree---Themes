export function generateAnimationsCss(project: ThemeProject): string {
  const cfg = project.config;
  const dur = `${cfg.animations.entranceDurationMs}ms`;
  const delay = `${cfg.animations.entranceDelayMs}ms`;
  const contSpeed = `${cfg.animations.continuousSpeedSec}s`;
  const iter = cfg.animations.iterationCount;
  const accentGlow = hexToRgbaString(cfg.colors.accentPrimary, (cfg.animations.continuousIntensity / 100) * 0.65);

  const entranceKeyframes: Record<string, string> = {
    none: '',
    'fade-in': `@keyframes lsEntrance { from { opacity: 0; } to { opacity: 1; } }`,
    'slide-up': `@keyframes lsEntrance { from { opacity: 0; transform: translateY(20px); } to { opacity: 1; transform: translateY(0); } }`,
    'slide-down': `@keyframes lsEntrance { from { opacity: 0; transform: translateY(-20px); } to { opacity: 1; transform: translateY(0); } }`,
    'zoom-in': `@keyframes lsEntrance { from { opacity: 0; transform: scale(0.92); } to { opacity: 1; transform: scale(1); } }`,
    reveal: `@keyframes lsEntrance { from { opacity: 0; transform: translateY(12px) scale(0.97); } to { opacity: 1; transform: translateY(0) scale(1); } }`,
    'blur-to-focus': `@keyframes lsEntrance { from { opacity: 0; filter: blur(8px); transform: translateY(10px); } to { opacity: 1; filter: blur(0); transform: translateY(0); } }`,
    staggered: `@keyframes lsEntrance { from { opacity: 0; transform: translateY(16px); } to { opacity: 1; transform: translateY(0); } }`,
  };

  let continuousRules = '';
  if (cfg.animations.continuous === 'pulse-glow' || cfg.animations.continuous === 'ambient-glow') {
    continuousRules = `
@keyframes lsPulseGlow {
  0%, 100% { box-shadow: 0 0 8px ${hexToRgbaString(cfg.colors.accentPrimary, 0.18)}; }
  50% { box-shadow: 0 0 ${Math.max(12, cfg.buttons.glowSpreadPx)}px ${accentGlow}; }
}
.button {
  animation: lsEntrance ${dur} cubic-bezier(0.16, 1, 0.3, 1) ${delay} both, lsPulseGlow ${contSpeed} ease-in-out ${iter};
}`;
  } else if (cfg.animations.continuous === 'moving-border-light' || cfg.animations.continuous === 'holographic-shift') {
    continuousRules = `
@keyframes lsGradientFlow {
  0% { background-position: 0% 50%; }
  50% { background-position: 100% 50%; }
  100% { background-position: 0% 50%; }
}
.button::after {
  content: "";
  position: absolute;
  inset: 0;
  background: linear-gradient(110deg, transparent 25%, ${hexToRgbaString(cfg.colors.accentPrimary, 0.2)} 50%, transparent 75%);
  background-size: 220% 100%;
  animation: lsGradientFlow ${contSpeed} linear ${iter};
  pointer-events: none;
  opacity: 0.65;
}`;
  }

  let hoverTransform = 'transform: translateY(-2px);';
  if (cfg.animations.microInteraction === 'scale-pop') {
    hoverTransform = 'transform: scale(1.025);';
  } else if (cfg.animations.microInteraction === 'magnetic-press') {
    hoverTransform = 'transform: translateY(-3px) scale(1.01);';
  }

  return `/* LinkStack Theme: ${project.name} — animations.css */
${entranceKeyframes[cfg.animations.entrance] ?? entranceKeyframes['fade-in']}

@keyframes lsGradientFlow {
  0% { background-position: 0% 50%; }
  50% { background-position: 100% 50%; }
  100% { background-position: 0% 50%; }
}

.fadein {
  ${cfg.animations.entrance === 'none' ? '' : `animation: lsEntrance ${dur} cubic-bezier(0.16, 1, 0.3, 1) both;`}
}

.button-entrance {
  ${cfg.animations.entrance === 'none' ? '' : `animation: lsEntrance ${dur} cubic-bezier(0.16, 1, 0.3, 1) ${delay} both;`}
}

${continuousRules}

.button-hover,
.credit-hover {
  transition: transform 0.18s cubic-bezier(0.16, 1, 0.3, 1), box-shadow 0.2s ease;
}

.button-hover:hover,
.button-hover:focus-visible,
.credit-hover:hover {
  ${hoverTransform}
}

.footer-hover {
  transition: transform 0.2s ease-out;
}

.footer-hover:hover {
  transform: translateY(-4px);
}

${
  cfg.animations.respectReducedMotion
    ? `@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
  }
}`
    : ''
}
`;
}

