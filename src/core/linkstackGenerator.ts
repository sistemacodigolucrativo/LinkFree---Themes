function buildInlineGeometryMarkup(cfg: ThemeConfig): string {
  const accent = cfg.colors.accentPrimary;
  const secondary = cfg.colors.accentSecondary;

  switch (cfg.geometry.layer) {
    case 'hexagons':
      return `<svg width="100%" height="100%" xmlns="http://www.w3.org/2000/svg"><defs><pattern id="ls-hex" width="60" height="52" patternUnits="userSpaceOnUse"><polygon points="30,2 56,16 56,40 30,50 4,40 4,16" fill="none" stroke="${accent}" stroke-width="0.9"/></pattern></defs><rect width="100%" height="100%" fill="url(#ls-hex)"/></svg>`;
    case 'luminous-circles':
      return `<svg width="100%" height="100%" viewBox="0 0 600 900" preserveAspectRatio="xMidYMid slice"><circle cx="300" cy="180" r="140" fill="none" stroke="${accent}" stroke-width="1" stroke-dasharray="6 6"/><circle cx="300" cy="180" r="215" fill="none" stroke="${secondary}" stroke-width="0.8"/><circle cx="300" cy="760" r="240" fill="none" stroke="${accent}" stroke-width="0.7" opacity="0.6"/></svg>`;
    case 'diagonal-lines':
      return `<svg width="100%" height="100%" xmlns="http://www.w3.org/2000/svg"><defs><pattern id="ls-diag" width="32" height="32" patternUnits="userSpaceOnUse" patternTransform="rotate(35)"><line x1="0" y1="0" x2="0" y2="32" stroke="${accent}" stroke-width="1"/></pattern></defs><rect width="100%" height="100%" fill="url(#ls-diag)"/></svg>`;
    case 'holographic-shards':
      return `<svg width="100%" height="100%" viewBox="0 0 600 900" preserveAspectRatio="xMidYMid slice"><polygon points="40,80 180,20 130,210" fill="${hexToRgbaString(accent, 0.14)}" stroke="${accent}" stroke-width="0.8"/><polygon points="550,140 420,240 570,350" fill="${hexToRgbaString(secondary, 0.14)}" stroke="${secondary}" stroke-width="0.8"/></svg>`;
    case 'abstract-waves':
      return `<svg width="100%" height="100%" viewBox="0 0 600 900" preserveAspectRatio="none"><path d="M0,180 C160,110 380,260 600,160" fill="none" stroke="${accent}" stroke-width="1.4"/><path d="M0,740 C220,660 390,820 600,720" fill="none" stroke="${secondary}" stroke-width="1.2"/></svg>`;
    case 'tech-frames':
      return `<div style="position:absolute;inset:16px;border:1px solid ${hexToRgbaString(accent, 0.3)};pointer-events:none;"></div>`;
    case 'dynamic-borders':
      return `<div style="position:absolute;inset:12px;border:2px solid ${accent};border-radius:16px;box-shadow:inset 0 0 28px ${hexToRgbaString(secondary, 0.35)};pointer-events:none;"></div>`;
    default:
      return '';
  }
}

